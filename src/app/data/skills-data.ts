/**
 * Get all skills for a specific archetype
 */
export function getSkillsForArchetype(archetype: DesignArchetype): {
  craft: Skill[];
  communication: Skill[];
  leadership: Skill[];
  business: Skill[];
} {
  const craftSkills = {
    'product-design': productDesignSkills,
    'ux-design-research': uxDesignResearchSkills,
    'visual-design': visualDesignSkills,
    'service-design': serviceDesignSkills,
    'interaction-design': interactionDesignSkills,
    'content-design': contentDesignSkills,
    'motion-design': motionDesignSkills,
    'design-systems': designSystemsSkills,
  }[archetype] || productDesignSkills;

  return {
    craft: craftSkills,
    communication: communicationSkills,
    leadership: leadershipSkills,
    business: businessSkills,
  };
}

/**
 * Get all skills in a single array for a specific archetype
 */
export function getAllSkillsForArchetype(archetype: DesignArchetype): Skill[] {
  const skillsByCategory = getSkillsForArchetype(archetype);
  return [
    ...skillsByCategory.craft,
    ...skillsByCategory.communication,
    ...skillsByCategory.leadership,
    ...skillsByCategory.business,
  ];
}

/**
 * Check if a skill is unlocked based on current role level
 */
export function isSkillUnlocked(skill: Skill, currentRoleLevel: number): boolean {
  return currentRoleLevel >= skill.unlockAtLevel;
}

/**
 * Get role level from role ID
 * Uses the actual level from careerRoles data
 */
export function getRoleLevelFromId(roleId: string | null): number {
  if (!roleId) return 0;
  
  // Find the role in careerRoles and return its level
  const role = careerRoles.find(r => r.id === roleId);
  return role?.level ?? 0;
}